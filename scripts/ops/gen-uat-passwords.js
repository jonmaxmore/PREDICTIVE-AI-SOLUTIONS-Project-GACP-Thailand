#!/usr/bin/env node
/**
 * scripts/ops/gen-uat-passwords.js
 *
 * Generates one random password per STAGING-WALKTHROUGH UAT role, writes them
 * to a local creds file (chmod 600), and prints a single-line JSON map to
 * stdout so the CALLING shell can capture it into a variable and hand it
 * straight to `uat-account-seed.js` via `docker exec -e` — never echoed back
 * out anywhere else. Called ONLY by scripts/ops/run-walkthrough.sh.
 *
 * The role -> canonical test-account id mapping below matches
 * apps/backend/prisma/seed-gacp.js exactly (that file is the single seed
 * source for these accounts — see its own header: "This is the ONLY seed
 * file for user accounts"):
 *   farmer    healthId   1186494077533  (APPLICANTS[0], seed-gacp.js:69)
 *   reviewer  providerId 1111111111111  (OFFICERS,      seed-gacp.js:96)
 *   auditor   providerId 2222222222222  (OFFICERS,      seed-gacp.js:104)
 *   scheduler providerId 3333333333333  (OFFICERS,      seed-gacp.js:123)
 *   account   providerId 4444444444444  (OFFICERS,      seed-gacp.js:131)
 *   admin     providerId 9876543210987  (ADMIN,         seed-gacp.js:87)
 *
 * Usage: node gen-uat-passwords.js <creds-file-path>
 */
'use strict';

const fs = require('fs');
const crypto = require('crypto');

const ROLES = [
  { key: 'farmer', idField: 'healthId', id: '1186494077533' },
  { key: 'reviewer', idField: 'providerId', id: '1111111111111' },
  { key: 'auditor', idField: 'providerId', id: '2222222222222' },
  { key: 'scheduler', idField: 'providerId', id: '3333333333333' },
  { key: 'account', idField: 'providerId', id: '4444444444444' },
  { key: 'admin', idField: 'providerId', id: '9876543210987' },
];

function genPassword() {
  // Fixed alnum prefix (so it trivially satisfies "at least one upper/lower/
  // digit" style policies without this script having to guess or read one) +
  // 16 random bytes, base64 with the non-alnum characters stripped so the
  // value is shell/JSON-safe without extra escaping.
  const random = crypto.randomBytes(16).toString('base64').replace(/[^A-Za-z0-9]/g, '');
  return `Uat2${random}`;
}

function main() {
  const credsPath = process.argv[2];
  if (!credsPath) {
    console.error('usage: gen-uat-passwords.js <creds-file-path>');
    process.exit(1);
  }

  const map = {};
  const lines = [
    `# ${credsPath.split('/').pop()}`,
    '# generated by scripts/ops/run-walkthrough.sh --seed-uat',
    '# chmod 600 — DO NOT commit, DO NOT paste into chat/logs/tickets.',
    '# Valid until the next --seed-uat run rotates these passwords again.',
    '',
  ];
  for (const role of ROLES) {
    const password = genPassword();
    map[role.key] = password;
    lines.push(`${role.key}\t${role.idField}=${role.id}\tpassword=${password}`);
  }

  fs.writeFileSync(credsPath, `${lines.join('\n')}\n`, { mode: 0o600 });
  fs.chmodSync(credsPath, 0o600);
  // Intentionally the ONLY output of this process — the caller captures it
  // into a shell variable and must not echo it back out.
  process.stdout.write(JSON.stringify(map));
}

main();
