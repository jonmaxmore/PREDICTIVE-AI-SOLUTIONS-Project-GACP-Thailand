/**
 * F3 และ F4 — "ไม่ทำ" คือคำตัดสิน ไม่ใช่งานที่ค้าง · ไฟล์นี้ทำให้มันเป็นกฎที่เครื่องถือไว้
 *
 * แผนการเงินเดิมสั่งสองอย่างที่ **ต้องไม่ทำ** และเหตุผลอยู่ในข้อมูลจริง ไม่ใช่ในรสนิยม:
 *
 *   F3  "เลิกคืน VAT = 0 สำหรับฝั่ง DTAM"  ← **กลับมติแล้ว 2026-09-11 ดูข้างล่าง**
 *
 *   F4  "เหลือ key namespace เดียว"
 *       การถอด namespace ออกทำให้ลายเซ็นบนใบเสร็จที่ออกด้วย namespace นั้นตรวจไม่ผ่าน —
 *       ความผิดพลาดตระกูลเดียวกับการ rotate กุญแจโดยไม่ดูว่ามันเซ็นอะไรไว้ (keys/README.md)
 *
 * ทั้งสองข้อจึงถูก **ปิดด้วยเส้นแบ่งเวลา** (services/billing/w14-boundary.js) แทนการลบ:
 * ของเก่าเปิดได้ต่อไป ของใหม่ในนามเดิมออกไม่ได้
 *
 * เทสนี้มีไว้เพื่อให้คนถัดไปที่อ่านแผนเดิมแล้วคิดว่า "ยังไม่ได้ทำ" เจอกฎก่อนเจอความว่าง
 */
'use strict';

const fs = require('fs');
const path = require('path');

const read = (rel) => fs.readFileSync(path.join(__dirname, '..', '..', rel), 'utf8');

/**
 * F3 — **กลับมติเมื่อ 2026-09-11** และบันทึกไว้ที่นี่แทนการลบทิ้ง
 *
 * เดิม F3 สั่งว่า "ห้ามเลิกคืน VAT = 0 สำหรับฝั่ง DTAM" เพราะสาขานั้นเข้าถึงได้เฉพาะ
 * เอกสารก่อนมติ W14 (staging: ใบเสนอราคา 16 ใบ · ใบแจ้งหนี้ฝั่งรัฐ 22 ใบ) ซึ่ง ณ เวลานั้น
 * กรมฯ เป็นผู้ออกคนละรายและได้รับยกเว้น VAT จริง ⇒ การแก้คือการเขียนประวัติศาสตร์ภาษีใหม่
 *
 * operator 2026-09-11 สั่งเลิกแยกค่าธรรมเนียมรัฐกับค่าบริการทั้งระบบ: *"เรามีราคานี้เท่านั้น
 * ต่อ 1 รูปแบบการปลูก แบบอื่นไม่ถูกต้อง เก็บกวาด และคลีนทิ้งให้หมด"* และสั่งถอดระบบนำส่งเงิน
 * ให้กรมออกทั้งชุด ⇒ ไม่มี "ฝั่ง DTAM" ให้ยกเว้น VAT อีกแล้ว สาขานั้นจึงถูกถอด
 *
 * เหตุผลเดิมของ F3 ไม่ผิด แต่ข้อเท็จจริงที่มันยืนอยู่หายไป: แพลตฟอร์มยังไม่ขึ้นใช้งานจริง
 * (demo/staging เท่านั้น) จึงไม่มีเอกสารภาษีของผู้เสียภาษีจริงให้ต้องพิมพ์ซ้ำ
 *
 * เก็บบล็อกนี้ไว้เป็นบันทึก ไม่ใช่เป็นด่าน — เพื่อให้คนที่อ่านเจอ F3 ในเอกสารเก่ารู้ว่ามันถูก
 * กลับเมื่อไรและด้วยเหตุใด แทนที่จะเจอความว่างเปล่าแล้วเดาเอง
 */
describe('F3 — ถูกกลับมติ 2026-09-11', () => {
    const src = read('services/quotation-line-items.js');

    test('ไม่มีสาขา VAT = 0 ของฝั่ง DTAM เหลืออยู่แล้ว', () => {
        expect(src).not.toMatch(/ISSUER_TYPES\.DTAM.*\)\s*\{\s*return 0;/s);
    });

    test('และไฟล์บอกเองว่าทำไมมันหายไป', () => {
        expect(src).toMatch(/ไม่มีฝั่งใดที่ VAT เป็นศูนย์อีกแล้ว/);
    });

    test('และประตูที่ออกเอกสารยังกันฝั่งที่เลิกใช้แล้วไม่ให้ถูกพิมพ์', () => {
        const boundary = read('services/billing/w14-boundary.js');
        expect(boundary).toMatch(/W14_RULING_AT/);
        expect(boundary).toMatch(/2026-08-22/);
        // ประตู API ยังเรียกเส้นแบ่งเวลา — แถวก่อนมติยังอ่านได้ตามเดิม
        expect(read('routes/api/applications/quotations.js')).toMatch(/assertIssuerSideRenderable/);

        // ตัวเรนเดอร์ไม่เรียกเส้นแบ่งแล้ว เพราะมันไม่ต้องถามว่า "แถวนี้เก่าพอจะพิมพ์ฝั่งรัฐไหม"
        // อีกต่อไป — ตั้งแต่ 2026-09-11 ไม่มีเอกสารในนามกรมให้พิมพ์เลยสักใบ มันจึงปฏิเสธ
        // issuerSide ที่ไม่ใช่ PLATFORM ทุกกรณี ซึ่ง **เข้มกว่า** เส้นแบ่งเวลา ไม่ใช่หลวมกว่า
        // ด่านที่ย้ายที่ต้องถูกตรึงที่ที่ใหม่ ไม่ใช่ปล่อยให้เทสชี้ไปที่ว่าง
        const renderer = read('services/pdf/invoice-template-service.js');
        expect(renderer).not.toMatch(/assertIssuerSideRenderable/);
        expect(renderer).toMatch(/issuerSide !== ISSUER_TYPES\.PLATFORM/);
        expect(renderer).toMatch(/INVALID_ISSUER_SIDE/);
    });
});

describe('F4 — key namespace ทั้งสองชุดต้องยังอยู่', () => {
    // เดิมอ่าน services/receipt-auto-sign-service.js — ไฟล์นั้นถูกลบไปทั้งใบพร้อม
    // ระบบสลิป (a4f6b154 "remove the bank-slip payment subsystem", operator: ลบทั้งหมด)
    // เพราะการจ่ายเงินเป็น Stripe + settle ด้วย webhook แล้ว ไม่มีใครเซ็นใบเสร็จอัตโนมัติ
    // จากสลิปอีก · ผลคือ readFileSync โยน ENOENT ตอน collect ทำให้ทั้งไฟล์ล้ม — F3 และ
    // ข้อสุดท้ายที่ไม่เกี่ยวข้องกันเลยก็ตายไปด้วย นานหลายรอบ gate
    //
    // แต่ "กฎ" ของ F4 ไม่ได้ตายตามไฟล์: สิ่งที่ F4 ห้าม คือการยุบ key namespace เหลือชุด
    // เดียว เพราะใบเสร็จที่เซ็นด้วย namespace เดิมจะตรวจไม่ผ่าน · ความสามารถนั้นอยู่ที่
    // services/crypto/signature-service.js (INT-11) และยังทำงานอยู่ เทสจึงเฝ้าที่นั่นแทน
    const src = read('services/crypto/signature-service.js');

    test('ยังเลือก namespace ตามผู้ออก ไม่ได้ยุบเหลือชุดเดียว', () => {
        expect(src).toMatch(/namespace/i);
        // ถ้าวันหนึ่งมีคนยุบจริง เทสนี้จะแดงพร้อมเหตุผลอยู่ข้างบน
        expect(src).toMatch(/DTAM|STATE/);
        // และกุญแจต่อ namespace ต้องยังโหลดได้จริง ไม่ใช่เหลือแค่คำในคอมเมนต์
        expect(src).toMatch(/namespaces/);
    });

    test('เอกสารกุญแจยังเตือนเรื่องการ rotate อยู่ — เหตุผลของ F4 อ้างมันโดยตรง', () => {
        const readme = read('keys/README.md');
        expect(readme).toMatch(/ห้าม rotate|DO NOT ROTATE/);
    });
});

describe('คำวินิจฉัยถูกบันทึกไว้ให้คนถัดไปอ่าน', () => {
    test('เอกสารออกแบบระบุชัดว่า F3/F4 เป็น "ไม่ทำ" พร้อมเหตุผล', () => {
        const design = read('../../docs/design/2026-09-05-finance-documents-design.md');
        expect(design).toMatch(/F3[^|]*\|[^|]*ไม่ทำ/);
        expect(design).toMatch(/F4[^|]*\|[^|]*ไม่ทำ/);
        expect(design).toMatch(/ประวัติศาสตร์ภาษี/);
    });
});
