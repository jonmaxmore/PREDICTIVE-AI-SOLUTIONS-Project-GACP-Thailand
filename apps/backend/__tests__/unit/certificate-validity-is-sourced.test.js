/**
 * อายุใบรับรองต้องมาจากที่เดียว และต้องรู้ว่ามันยังไม่ได้ยืนยัน
 *
 * ค่าเดิมคือ `const validYears = 3;` ฝังกลางฟังก์ชันออกใบ พร้อมคอมเมนต์ `// Standard GACP`
 * ที่ทำให้มันอ่านเหมือนเป็นตัวเลขของมาตรฐาน · ค้นเอกสารทางการของกรมสองฉบับเมื่อ 2026-09-11
 * (แบบ กทล.1 และข้อกำหนดฯ Thailand Cannabis GACP) แล้ว **ไม่มีฉบับใดระบุอายุใบรับรอง**
 *
 * ISO/IEC 17065:2012 §7.7.1(e) บังคับให้ใบระบุ "the term or expiry date of certification"
 * — ต้องมีอายุ แต่ไม่ได้กำหนดว่ากี่ปี · ความยาวเป็นของ scheme owner (กรมฯ)
 *
 * operator 2026-09-11: "ตั้งเป็น 1 ปีก่อน เดี๋ยวคอนเฟิร์มอีกที"
 *
 * ไฟล์นี้ไม่ได้ตรึงว่า "หนึ่งปีถูก" — มันตรึงสองอย่างที่ถูกจริง:
 *   1. ตัวเลขอยู่ที่เดียว ไม่ใช่เลขลอยในฟังก์ชัน
 *   2. ตัวเลขที่ยังไม่ยืนยันต้องมีป้ายบอก ไม่ใช่ปล่อยให้คนถัดไปอ่านว่าเป็นข้อเท็จจริง
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { CERTIFICATE } = require('../../config/business-rules');

describe('อายุใบรับรอง', () => {
    it('เป็นค่าที่ operator ยืนยันแล้ว — หนึ่งปี', () => {
        expect(CERTIFICATE.VALIDITY_YEARS).toBe(1);
    });

    it('ไม่มีเลขอายุลอยอยู่ในโค้ดออกใบอีก', () => {
        const source = fs.readFileSync(
            path.join(__dirname, '../../services/certificate-service.js'), 'utf8',
        );
        // จับเฉพาะการกำหนดค่า ไม่จับคอมเมนต์ที่อธิบายว่าเลขเก่าคืออะไร
        expect(source).not.toMatch(/const\s+validYears\s*=\s*\d/);
        expect(source).toContain('CERTIFICATE.VALIDITY_YEARS');
    });

    it('ที่ที่นิยามมันบอกว่าตัวเลขนี้เป็นมติของเรา ไม่ใช่การอ้างเอกสารกรม', () => {
        const source = fs.readFileSync(
            path.join(__dirname, '../../config/business-rules.js'), 'utf8',
        );
        // ข้อเท็จจริงที่ยังเป็นจริงหลัง operator ยืนยัน: เอกสารกรมไม่ได้ระบุอายุ
        // ⇒ ถ้ากรมประกาศอายุที่ต่างไป นี่คือจุดที่ต้องกลับมาแก้ และเป็นการแก้มติของเรา
        // ไม่ใช่การแก้ความผิดพลาด · ตัวเลขที่ไม่บอกว่าใครเป็นคนตัดสิน จะถูกอ่านว่าเป็น
        // ของมาตรฐาน แบบเดียวกับ `// Standard GACP` ที่มันมาแทน
        expect(source).toContain('ไม่มีฉบับใดระบุอายุใบรับรอง');
        expect(source).toContain('การตัดสินของเจ้าของ scheme');
    });
});
