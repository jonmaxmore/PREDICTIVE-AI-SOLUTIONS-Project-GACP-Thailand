/** วันที่มติ — ค่าคงที่ที่ชี้กลับไปยังมติจริง ไม่ใช่วันที่ใครสักคนจำได้ */
const W14_RULING_AT = new Date('2026-08-22T00:00:00.000Z');

const W14_ISSUER_SIDE_RETIRED = 'W14_ISSUER_SIDE_RETIRED';

/**
 * แถวนี้เป็นเอกสารของโมเดลเก่าหรือไม่
 *
 * แถวที่ไม่มีวันที่ที่อ่านได้ **ไม่ถือว่าเป็นของเก่า** — การเดาไปทางผ่อนปรนตรงนี้ คือการเปิดช่อง
 * ให้แถวที่รูปร่างผิดกลายเป็นใบผ่าน
 */
function isPreW14Document(row) {
    const raw = row && row.createdAt;
    if (!raw) { return false; }
    const at = raw instanceof Date ? raw : new Date(String(raw));
    if (Number.isNaN(at.getTime())) { return false; }
    return at < W14_RULING_AT;
}

/**
 * ประตูเอกสารเรียกก่อนเรนเดอร์ในนามผู้ออกฝั่งใดฝั่งหนึ่ง
 *
 * ไม่มีแถว = ไม่ใช่หน้าที่ของด่านนี้ (ผู้เรียกตอบ 404 อยู่แล้ว) · ฝั่งบริษัทผ่านเสมอ
 * เพราะเป็นผู้ออกรายเดียวที่เหลืออยู่
 */
/**
 * ใบแจ้งหนี้ใบนี้เป็นฝั่งรัฐหรือไม่
 *
 * `invoice-template-service` เลือกเทมเพลตใบเสร็จจาก isStateFee แล้วผู้เรียกแต่ละที่ก็เดา
 * เอาเองจากชื่อ serviceType · รวมไว้ที่เดียวเพื่อให้เส้นแบ่ง W14 ถามคำถามเดียวกับที่
 * ตัวเลือกเทมเพลตถาม ไม่ใช่คำถามที่คล้ายกัน
 *
 * ข้อมูลจริง (staging, 2026-09-05): PHASE_1_STATE_FEE 10 ใบ · PHASE_2_STATE_FEE 12 ใบ
 * สร้าง 2026-06-05 ถึง 07-16 · **ไม่มีใบไหนเกิดหลังมติ W14 เลย**
 */
function isStateFeeDocument(row) {
    const t = row && row.serviceType;
    return typeof t === 'string' && t.trim().toUpperCase().endsWith('STATE_FEE');
}

function assertIssuerSideRenderable({ issuerSide, row } = {}) {
    if (!row) { return; }
    const side = String(issuerSide || '').trim().toUpperCase();
    if (side !== 'DTAM') { return; }
    if (isPreW14Document(row)) { return; }

    const err = new Error(
        `The DTAM issuer side was retired by the W14 ruling (2026-08-22); `
        + `document ${row.quotationNumber || row.invoiceNumber || ''} was created after it`,
    );
    err.code = W14_ISSUER_SIDE_RETIRED;
    err.statusCode = 409;
    err.messageTh =
        'เอกสารในนามกรมฯ ถูกยกเลิกโดยมติ W14 (22 ส.ค. 2569) ซึ่งกำหนดให้มีผู้ออกเอกสารรายเดียว '
        + 'และคิด VAT 7% บนค่าบริการทั้งก้อน · เอกสารที่ออกก่อนมติยังเปิดดูได้ตามเดิม '
        + 'แต่เอกสารที่เกิดหลังมติจะออกในนามกรมฯ ไม่ได้';
    throw err;
}

module.exports = {
    W14_RULING_AT,
    isStateFeeDocument,
    W14_ISSUER_SIDE_RETIRED,
    isPreW14Document,
    assertIssuerSideRenderable,
};
