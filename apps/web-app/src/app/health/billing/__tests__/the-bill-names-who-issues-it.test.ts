/**
 * หน้าสรุปยอดต้องพูดตามโมเดลที่ใช้จริง — บริษัทจัดการทั้งหมด ไม่มีตัวแทน
 *
 * มติ operator 2026-09-07: "ไม่มีตัวแทนแล้ว บริษัทเป็นคนจัดการทั้งหมด"
 * ต่อจากมติ W14 (2026-08-22) ที่ให้หนึ่งคำขอมีใบเสนอราคาใบเดียว ออกในนามบริษัท
 * ถือราคาทั้งก้อน + VAT 7% ของค่าบริการทั้งหมด แล้วบริษัทเคลียร์กับกรมนอกระบบ
 *
 * ⇒ ฝั่ง DTAM จะไม่มีเอกสารเลยสำหรับคำขอใหม่ทุกใบ ตลอดไป
 *
 * แต่หน้าจอยังพิมพ์การ์ด "ค่าธรรมเนียมรัฐ (DTAM) — ฿0.00 · VAT-exempt ตาม ม.77/1(10)"
 * ค้างไว้ข้างการ์ด "ค่าบริการแพลตฟอร์ม ฿105,930" · เกษตรกรอ่านได้อย่างเดียวว่า
 * "ไม่มีค่าธรรมเนียมรัฐ" ทั้งที่ค่ารัฐคือ 90,000 หรือ 85% ของบิล — มันอยู่ข้างในยอดของบริษัท
 * และบรรทัด "VAT-exempt" ก็ไม่มีอะไรให้ยกเว้น เพราะการ์ดนั้นว่างเปล่า
 *
 * สองอย่างที่ต้องจริง:
 *   1. ไม่โชว์การ์ดของฝั่งที่ไม่มีเอกสารเลย (คำขอก่อน W14 ที่มีคู่จริง ยังโชว์ได้เหมือนเดิม)
 *   2. การ์ดของบริษัทต้องบอกว่าเป็นผู้ออกเอกสารทั้งหมด ไม่ใช่ป้ายว่า "ค่าบริการแพลตฟอร์ม"
 *      ซึ่งอ่านเหมือนว่า 105,930 เป็นค่าบริการของแพลตฟอร์มล้วน
 */
import fs from 'node:fs';
import path from 'node:path';

const SRC = fs.readFileSync(path.join(__dirname, '..', 'client-view.tsx'), 'utf8');
const CODE = SRC.replace(/\{\/\*[\s\S]*?\*\/\}/g, '').replace(/\/\*[\s\S]*?\*\//g, '');

describe('การ์ดสรุปยอดตามผู้ออกเอกสาร', () => {
    it('ไม่พิมพ์ฝั่งที่ไม่มีเอกสารเลย', () => {
        expect(CODE).toMatch(/hasDocuments|invoiceCount\s*>\s*0|documentCount\s*>\s*0/);
    });

    it('ไม่ประกาศ VAT-exempt บนการ์ดที่ไม่มีอะไรอยู่ในนั้น', () => {
        // บรรทัดกฎหมายต้องผูกกับการ์ดที่มีเอกสารจริงเท่านั้น
        expect(CODE).not.toMatch(/subtitle="VAT-exempt[^"]*"\s*\n\s*summary=\{statement\.summary\.dtamSide\}/);
    });

    it('การ์ดของบริษัทบอกว่าเป็นผู้ออกเอกสาร ไม่ใช่แค่ "ค่าบริการแพลตฟอร์ม"', () => {
        expect(CODE).toMatch(/ผู้ออกเอกสาร|ออกโดยบริษัท|ออกในนามบริษัท/);
    });
});
