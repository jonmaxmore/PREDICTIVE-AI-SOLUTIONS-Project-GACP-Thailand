import type { PaymentRecord } from '@/lib/services/payment-service';

/** งวดที่ 1 จ่ายได้เมื่อคำขออยู่สถานะเหล่านี้ — กระจกของ PAYABLE_STATES.M1 */
const PHASE1_PAYABLE = new Set(['SUBMITTED', 'PENDING_DOC_FEE']);
/** งวดที่ 2 จ่ายได้เมื่อเอกสารผ่านแล้วเท่านั้น — กระจกของ PAYABLE_STATES.M2 */
const PHASE2_PAYABLE = new Set(['DOC_APPROVED', 'PENDING_AUDIT_FEE']);

export type PhaseKey = 'PHASE_1' | 'PHASE_2';

export type PhaseDueState =
    /** จ่ายได้ตอนนี้ — คำขออยู่ในสถานะที่เปิดให้ชำระงวดนี้ และยังมียอดค้าง */
    | 'DUE_NOW'
    /** ยังไม่ถึงคิว — ยอดถูกตั้งไว้แล้วแต่ประตูยังไม่เปิด */
    | 'NOT_YET'
    /** ชำระครบแล้ว */
    | 'SETTLED'
    /** ตอบไม่ได้ — ไม่รู้สถานะคำขอ จึงไม่อ้างอะไรทั้งสิ้น */
    | 'UNKNOWN';

/**
 * เท่าที่กฎนี้ต้องรู้เกี่ยวกับใบแจ้งหนี้หนึ่งใบ — สองค่าที่ชั้น mapping คำนวณให้แล้ว
 * บวกเจ้าของใบ เพราะกล่องงวดหนึ่งกล่องอาจมีใบของหลายคำขอปนกันอยู่ (ดู phaseDueState)
 */
export type DueInvoice = Pick<PaymentRecord, 'isPaid' | 'isCancelled' | 'applicationId'>;

/**
 * ใบนี้ยังเป็นหนี้ที่ผู้ยื่นต้องจ่ายอยู่ไหม
 *
 * ใบที่ยกเลิกแล้วไม่ใช่หนี้ — ไม่มีใครเก็บเงินตามใบนั้นได้ · ค่าที่ยังไม่ถูกเซ็ต
 * (ผู้เรียกที่ไม่ได้ผ่านชั้น mapping) นับเป็นหนี้ไว้ก่อน เพราะบอกว่า "ชำระครบแล้ว"
 * ผิดคือผู้ยื่นพลาดการจ่ายและคำขอค้างเงียบ ๆ ซึ่งแย่กว่าการเตือนเกิน
 */
export function isOutstanding(invoice: DueInvoice): boolean {
    if (invoice.isCancelled) return false;
    if (invoice.isPaid) return false;
    return true;
}

/**
 * งวดนี้อยู่ในสถานะไหน เมื่อมองจากคำขอที่มันสังกัด
 *
 * ข้อจำกัดที่ต้องรู้: หน้าชำระเงินจัดกลุ่มด้วย "งวด" อย่างเดียว ไม่ได้แยกด้วยคำขอ
 * (client-view.tsx grouped) ผู้ยื่นที่มีหลายคำขอจึงเห็นใบของทุกคำขอกองรวมในกล่อง
 * "งวดที่ 1" กล่องเดียว · สถานะที่ส่งเข้ามาเป็นของคำขอเดียวเท่านั้น ดังนั้นถ้ากล่องนี้
 * มีใบของคำขออื่นปนอยู่ กฎนี้จะไม่ยอมตอบ — ตอบ UNKNOWN แทนการเดาแทนเจ้าของเงิน
 * (การแยกกลุ่มตามคำขอเป็นงานคนละใบ — รายงาน 2026-09-10)
 *
 * @param phase             งวดที่กำลังถาม
 * @param applicationStatus สถานะคำขอ ณ ตอนนี้ (จากเซิร์ฟเวอร์ ไม่ใช่จากที่หน้าจอเดา)
 * @param invoices          ใบแจ้งหนี้ทุกใบในกล่องงวดนี้ (อาจปนหลายคำขอ)
 * @param applicationId     คำขอที่ applicationStatus เป็นของมัน
 */
export function phaseDueState(
    phase: PhaseKey,
    applicationStatus: string | null | undefined,
    invoices: ReadonlyArray<DueInvoice>,
    applicationId?: string | null,
): PhaseDueState {
    const outstanding = invoices.filter((inv) => isOutstanding(inv)).length;

    // ใบของคำขออื่นปนอยู่ ⇒ สถานะที่ได้มาไม่ได้ตัดสินทั้งกล่อง
    if (applicationId && invoices.some((inv) => inv.applicationId && inv.applicationId !== applicationId)) {
        return outstanding === 0 ? 'SETTLED' : 'UNKNOWN';
    }

    // ไม่มีอะไรค้าง = จบแล้ว · ตอบได้โดยไม่ต้องรู้สถานะคำขอ เพราะไม่มีอะไรให้จ่าย
    if (outstanding === 0) return 'SETTLED';

    // มียอดค้าง แต่ไม่รู้สถานะคำขอ ⇒ ไม่อ้างว่าจ่ายได้และไม่อ้างว่าจ่ายไม่ได้
    const status = String(applicationStatus ?? '').trim().toUpperCase();
    if (!status) return 'UNKNOWN';

    const payable = phase === 'PHASE_1' ? PHASE1_PAYABLE : PHASE2_PAYABLE;
    return payable.has(status) ? 'DUE_NOW' : 'NOT_YET';
}

